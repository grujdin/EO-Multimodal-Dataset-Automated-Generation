"""rdf_ingestion_script_taxonomy_only.py"""
from __future__ import annotations
import calendar, pathlib, re
import pandas as pd
from rdflib import Dataset, Graph, Namespace, URIRef, Literal, BNode
from rdflib.namespace import RDF, RDFS, XSD, SKOS

# ---------- CONFIG ----------
SPREADSHEET  = r"D:/ProjDB/GAUL/public_emdat_GDIS_GAUL_FIDs.xlsx"
TAXONOMY_TTL = r"C:/Users/JOHN/PycharmProjects/JSTARS/.venv/data/graphdb_import/hazard_taxonomy.ttl"  # generated by Patch A
OUT_TRIG     = r"C:/Users/JOHN/PycharmProjects/JSTARS/.venv/data/graphdb_import/emdat_events_all.trig"
TARGET_GRAPH = "http://example.org/kg/emdat/events/all"

# ---------- NAMESPACES ----------
E    = Namespace("http://example.org/eomdg/")
GAUL = Namespace("http://example.org/gaul/")
CONT = Namespace("http://example.org/continent/")
SUBC = Namespace("http://example.org/subcontinent/")
GEO  = Namespace("http://www.opengis.net/ont/geosparql#")
TIME = Namespace("http://www.w3.org/2006/time#")

# ---------- HELPERS ----------
cam = lambda s: re.sub(r"[^0-9A-Za-z]+", " ", str(s)).title().replace(" ", "")

def safe_date(y, m, d, is_start):
    if pd.isna(y):
        return None
    Y = int(y)
    M = 1 if (pd.isna(m) and is_start) else (12 if pd.isna(m) else int(m))
    D = 1 if (pd.isna(d) and is_start) else (calendar.monthrange(Y, M)[1] if pd.isna(d) else int(d))
    return Literal(f"{Y:04d}-{M:02d}-{D:02d}", datatype=XSD.date), Literal("inferred" if (pd.isna(m) or pd.isna(d)) else "reported")

class Taxonomy:
    def __init__(self, ttl_path: str):
        self.g = Graph()
        self.g.parse(ttl_path, format="turtle")
        self.g.bind("eomdg", E); self.g.bind("skos", SKOS)
        # Build a map from key → subtype URI
        self.by_key = {}
        for s in self.g.subjects(RDF.type, E.HazardSubtype):
            for k in self.g.objects(s, SKOS.notation):
                if isinstance(k, Literal):
                    self.by_key[str(k)] = s

    def _super_of(self, node: URIRef, target_cls: URIRef) -> URIRef | None:
        """Climb rdfs:subClassOf* to find a superclass typed as target_cls."""
        seen = set([node])
        frontier = [node]
        while frontier:
            cur = frontier.pop()
            if (cur, RDF.type, target_cls) in self.g:
                return cur
            for sup in self.g.objects(cur, RDFS.subClassOf):
                if sup not in seen:
                    seen.add(sup)
                    frontier.append(sup)
        return None

    def resolve_chain(self, key: str):
        sub = self.by_key.get(str(key))
        if not sub:
            raise KeyError(f"No HazardSubtype with skos:notation='{key}' in taxonomy")
        typ  = self._super_of(sub, E.HazardType)
        subg = self._super_of(sub, E.HazardSubgroup)
        grp  = self._super_of(sub, E.HazardGroup)
        return grp, subg, typ, sub

# ---------- LOAD ----------
TAX = Taxonomy(TAXONOMY_TTL)
df  = pd.read_excel(SPREADSHEET)

# ---------- DATASET/GRAPH ----------
ds = Dataset()
for pfx, ns in [("eomdg", E),("gaul", GAUL),("cont", CONT),("subc", SUBC),("geo", GEO),("time", TIME),("skos", SKOS)]:
    ds.bind(pfx, ns)
ctx = ds.get_context(URIRef(TARGET_GRAPH))

processed = set()

for _, row in df.iterrows():
    obs = URIRef(E[f"Observation/{row['Unique Code']}"])
    evt = URIRef(E[f"DisasterEvent/{row['DisNo.']}"])

    # Observation
    ctx.add((obs, RDF.type, E.DisasterObservation))
    ctx.add((obs, E.relatedEvent, evt))
    if pd.notna(row.get("Location")):
        ctx.add((obs, E.locationName, Literal(row["Location"])))
    for fid_col, prop in (("FID_1", E.adminUnitLevel1), ("FID_2", E.adminUnitLevel2)):
        if pd.notna(row.get(fid_col)):
            ctx.add((obs, prop, URIRef(GAUL[f"AdminUnit/{int(row[fid_col])}"])))

    # Event (once)
    if evt not in processed:
        processed.add(evt)
        ctx.add((evt, RDF.type, E.DisasterEvent))
        if pd.notna(row.get("Event Name")):
            ctx.add((evt, RDFS.label, Literal(row["Event Name"])))
        if pd.notna(row.get("External IDs")):
            for eid in str(row["External IDs"]).split(","):
                ctx.add((evt, E.externalID, Literal(eid.strip())))
        if pd.notna(row.get("ISO")):
            ctx.add((evt, E.countryCode, Literal(row["ISO"])))
        for col, p in (("Entry Date", E.entryDate),("Last Update", E.lastUpdate)):
            if pd.notna(row.get(col)):
                ctx.add((evt, p, Literal(pd.to_datetime(row[col]).isoformat(), datatype=XSD.dateTime)))

        # Hazard chain from key → subtype → type/subgroup/group
        key = str(row["Classification Key"]).strip()
        try:
            grp, subg, typ, sub = TAX.resolve_chain(key)
            ctx.add((evt, E.hasHazardGroup, grp))
            ctx.add((evt, E.hasHazardSubgroup, subg))
            ctx.add((evt, E.hasHazardType, typ))
            ctx.add((evt, E.hasHazardSubtype, sub))
        except KeyError as ex:
            print("⚠", ex)

        # Location point (GeoSPARQL WKT with SRID)
        lat, lon = row.get("Latitude"), row.get("Longitude")
        if pd.notna(lat) and pd.notna(lon):
            pt = BNode()
            ctx.add((pt, RDF.type, GEO.Geometry))
            ctx.add((pt, GEO.asWKT, Literal(f"SRID=4326; POINT({lon} {lat})", datatype=GEO.wktLiteral)))
            ctx.add((evt, E.hasLocationGeometry, pt))

        # Time (OWL-Time instants)
        def add_time(pred, y, m, d, start):
            sd = safe_date(y, m, d, start)
            if not sd: return
            dat, qual = sd
            inst = BNode()
            ctx.add((inst, RDF.type, TIME.Instant))
            ctx.add((inst, TIME.inXSDDate, dat))
            ctx.add((evt, pred, inst))
            ctx.add((evt, E["startDateQuality" if start else "endDateQuality"], qual))
        add_time(TIME.hasBeginning, row["Start Year"], row["Start Month"], row["Start Day"], True)
        add_time(TIME.hasEnd,       row["End Year"],   row["End Month"],   row["End Day"],   False)

# Serialize
pathlib.Path(OUT_TRIG).parent.mkdir(parents=True, exist_ok=True)
ds.serialize(destination=str(OUT_TRIG), format="trig")
print("✅ TriG written to", OUT_TRIG)
